#!/usr/bin/env python3
"""Run Rulesync and validate repository-local compatibility projections."""

from __future__ import annotations

import argparse
import json
import shutil
import stat
import subprocess
import sys
from collections.abc import Iterable, Sequence
from pathlib import Path

from _commands import run_npm_exec

REPO_ROOT = Path(__file__).resolve().parents[1]
RULESYNC_CONFIG = REPO_ROOT / "rulesync.jsonc"
RULESYNC_LOCK = REPO_ROOT / "rulesync.lock"
SKILLS_LOCK = REPO_ROOT / "skills-lock.json"
SKILLS_ROOT = REPO_ROOT / ".rulesync" / "skills"
CLAUDE_BRIDGE_NAME = "CLAUDE.md"
CLAUDE_BRIDGE_MARKER = (
    "<!-- Generated by scripts/rulesync.py from sibling AGENTS.md. -->"
)
CLAUDE_BRIDGE_CONTENT = f"{CLAUDE_BRIDGE_MARKER}\n\n@AGENTS.md\n"

_SOURCE_ACTIONS: dict[str, tuple[str, ...]] = {
    "install": ("install", "--frozen"),
    "update": ("install", "--update"),
}
_ACTIONS: dict[str, tuple[str, ...]] = {
    "preview": ("generate", "--dry-run"),
    "generate": ("generate",),
    "check": ("generate", "--check"),
    "doctor": ("doctor", "--strict"),
}
_SKILL_PROJECTION_ROOTS = (
    Path(".agents") / "skills",
    Path(".claude") / "skills",
    Path(".github") / "skills",
)


def _run(args: Sequence[str]) -> int:
    return run_npm_exec("rulesync@latest", "rulesync", args, cwd=REPO_ROOT)


def _load_jsonc(path: Path) -> object:
    text = path.read_text(encoding="utf-8")
    output: list[str] = []
    index = 0
    in_string = False
    escaped = False

    while index < len(text):
        char = text[index]
        next_char = text[index + 1] if index + 1 < len(text) else ""
        if in_string:
            output.append(char)
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                in_string = False
            index += 1
            continue
        if char == '"':
            in_string = True
            output.append(char)
            index += 1
            continue
        if char == "/" and next_char == "/":
            index += 2
            while index < len(text) and text[index] not in "\r\n":
                index += 1
            continue
        if char == "/" and next_char == "*":
            index += 2
            while index < len(text):
                if text[index : index + 2] == "*/":
                    index += 2
                    break
                if text[index] in "\r\n":
                    output.append(text[index])
                index += 1
            else:
                raise ValueError(f"unterminated JSONC comment: {path}")
            continue
        if char == ",":
            lookahead = index + 1
            while lookahead < len(text) and text[lookahead].isspace():
                lookahead += 1
            if lookahead < len(text) and text[lookahead] in "}]":
                index += 1
                continue
        output.append(char)
        index += 1

    return json.loads("".join(output))


def _is_link(path: Path) -> bool:
    try:
        if path.is_symlink():
            return True
        is_junction = getattr(path, "is_junction", None)
        return bool(is_junction and is_junction())
    except (OSError, RuntimeError):
        return True


def _path_has_link_component(path: Path) -> bool:
    try:
        relative_path = path.relative_to(REPO_ROOT)
    except ValueError:
        return True

    current = REPO_ROOT
    for component in relative_path.parts:
        current /= component
        if _is_link(current):
            return True
    return False


def _safe_skill_projection_root(root: Path) -> bool:
    if _path_has_link_component(root):
        return False
    try:
        resolved_root = root.resolve(strict=False)
        resolved_root.relative_to(REPO_ROOT.resolve(strict=True))
    except (OSError, RuntimeError, ValueError):
        return False
    return True


def _local_skill_names() -> set[str] | None:
    if _path_has_link_component(SKILLS_ROOT):
        return None

    try:
        root_mode = SKILLS_ROOT.lstat().st_mode
    except FileNotFoundError:
        return set()
    except OSError:
        return None

    if not stat.S_ISDIR(root_mode):
        return None

    try:
        paths = sorted(SKILLS_ROOT.iterdir(), key=lambda item: item.name.casefold())
    except OSError:
        return None

    names: set[str] = set()
    for path in paths:
        if path.name == ".curated":
            continue
        try:
            if _is_link(path):
                return None
            path_mode = path.lstat().st_mode
            if not stat.S_ISDIR(path_mode):
                continue
            skill_file = path / "SKILL.md"
            if _is_link(skill_file):
                return None
            skill_file_mode = skill_file.lstat().st_mode
            if stat.S_ISREG(skill_file_mode):
                names.add(path.name)
        except FileNotFoundError:
            continue
        except OSError:
            return None
    return names


def _source_skill_names(config: object, lock: object) -> set[str]:
    if not isinstance(config, dict) or not isinstance(lock, dict):
        raise ValueError("Rulesync config and lock must be JSON objects")

    names: set[str] = set()
    config_sources = config.get("sources", [])
    if not isinstance(config_sources, list):
        raise ValueError("Rulesync config sources must be a list")
    for source in config_sources:
        if not isinstance(source, dict):
            raise ValueError("Rulesync config source must be an object")
        skills = source.get("skills", [])
        if not isinstance(skills, list):
            raise ValueError("Rulesync config source skills must be a list")
        for name in skills:
            if not isinstance(name, str) or not name:
                raise ValueError(
                    "Rulesync config Skill name must be a non-empty string"
                )
            names.add(name)

    lock_sources = lock.get("sources", {})
    if not isinstance(lock_sources, dict):
        raise ValueError("Rulesync lock sources must be an object")
    for source in lock_sources.values():
        if not isinstance(source, dict):
            raise ValueError("Rulesync lock source must be an object")
        skills = source.get("skills", {})
        if not isinstance(skills, dict):
            raise ValueError("Rulesync lock source skills must be an object")
        for name in skills:
            if not isinstance(name, str) or not name:
                raise ValueError("Rulesync lock Skill name must be a non-empty string")
            names.add(name)
    return names


def _skills_cli_skill_names() -> set[str] | None:
    if _path_has_link_component(SKILLS_LOCK):
        return None

    try:
        lock_mode = SKILLS_LOCK.lstat().st_mode
    except FileNotFoundError:
        return set()
    except OSError:
        return None

    if not stat.S_ISREG(lock_mode):
        return None

    try:
        lock = json.loads(SKILLS_LOCK.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None

    if not isinstance(lock, dict):
        return None
    skills = lock.get("skills")
    if not isinstance(skills, dict):
        return None
    if any(not isinstance(name, str) or not name for name in skills):
        return None
    return set(skills)


def _declared_skill_names() -> set[str] | None:
    if _path_has_link_component(RULESYNC_CONFIG) or _path_has_link_component(
        RULESYNC_LOCK
    ):
        print(
            "warning: skipping stale Rulesync Skill prune: "
            "config or lock path contains a symlink/junction",
            file=sys.stderr,
        )
        return None
    try:
        if not RULESYNC_CONFIG.is_file() or not RULESYNC_LOCK.is_file():
            return None
        config = _load_jsonc(RULESYNC_CONFIG)
        lock = _load_jsonc(RULESYNC_LOCK)
        local_names = _local_skill_names()
        if local_names is None:
            raise ValueError("local Rulesync Skill source is unavailable or unsafe")
        skills_cli_names = _skills_cli_skill_names()
        if skills_cli_names is None:
            raise ValueError("Skills CLI lock is unavailable or invalid")
        return local_names | _source_skill_names(config, lock) | skills_cli_names
    except (OSError, ValueError) as error:
        print(
            f"warning: skipping stale Rulesync Skill prune: {error}",
            file=sys.stderr,
        )
        return None


def _skill_projection_roots() -> tuple[Path, ...]:
    return tuple(REPO_ROOT / relative_path for relative_path in _SKILL_PROJECTION_ROOTS)


def _stale_skill_directories(expected_names: set[str]) -> list[Path]:
    normalized_names = {name.casefold() for name in expected_names}
    stale: list[Path] = []
    for root in _skill_projection_roots():
        if not _safe_skill_projection_root(root):
            continue
        try:
            if not root.is_dir():
                continue
            paths = sorted(root.iterdir(), key=lambda item: item.name.casefold())
        except OSError as error:
            print(
                f"warning: skipping stale Rulesync Skill prune for {root}: {error}",
                file=sys.stderr,
            )
            continue
        for path in paths:
            try:
                if _is_link(path) or not path.is_dir():
                    continue
                if path.name.casefold() in normalized_names:
                    continue
                if (path / "SKILL.md").is_file():
                    stale.append(path)
            except OSError as error:
                print(
                    f"warning: skipping stale Rulesync Skill candidate {path}: {error}",
                    file=sys.stderr,
                )
    return stale


def _prune_stale_skill_directories(paths: Iterable[Path]) -> None:
    roots = set(_skill_projection_roots())
    for path in sorted(set(paths), key=lambda item: item.as_posix()):
        if path.parent not in roots or not _safe_skill_projection_root(path.parent):
            raise RuntimeError(
                f"refusing to prune outside Skill projection root: {path}"
            )
        try:
            if _is_link(path) or not path.is_dir() or not (path / "SKILL.md").is_file():
                continue
            shutil.rmtree(path)
        except OSError as error:
            raise RuntimeError(
                f"failed to prune stale Skill directory: {path}"
            ) from error
        print(f"pruned stale Rulesync Skill directory: {path.relative_to(REPO_ROOT)}")


def _run_generate() -> int:
    expected_names = _declared_skill_names()
    if expected_names is None:
        return _run(_ACTIONS["generate"])

    stale_before = _stale_skill_directories(expected_names)
    returncode = _run(_ACTIONS["generate"])
    if returncode != 0:
        return returncode

    stale_after = _stale_skill_directories(expected_names)
    _prune_stale_skill_directories((*stale_before, *stale_after))
    return 0


def _tracked_diff() -> str:
    result = subprocess.run(
        ["git", "diff", "--no-ext-diff", "--binary"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        raise RuntimeError("git diff failed while validating generated projections.")
    return result.stdout


def _repository_paths() -> list[Path]:
    result = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        raise RuntimeError("git ls-files failed while discovering instruction files.")
    return [Path(line) for line in result.stdout.splitlines() if line]


def _agent_instruction_paths() -> list[Path]:
    return sorted(path for path in _repository_paths() if path.name == "AGENTS.md")


def _claude_bridge_outputs() -> dict[Path, str]:
    return {
        REPO_ROOT / agents_path.with_name(CLAUDE_BRIDGE_NAME): CLAUDE_BRIDGE_CONTENT
        for agents_path in _agent_instruction_paths()
    }


def _existing_claude_bridge_paths() -> set[Path]:
    result: set[Path] = set()
    for relative_path in _repository_paths():
        if relative_path.name != CLAUDE_BRIDGE_NAME:
            continue
        path = REPO_ROOT / relative_path
        if path.is_file() and path.read_text(encoding="utf-8").startswith(
            CLAUDE_BRIDGE_MARKER
        ):
            result.add(path)
    return result


def _check_claude_bridges() -> int:
    expected = _claude_bridge_outputs()
    actual_paths = _existing_claude_bridge_paths()
    stale = sorted(actual_paths - expected.keys())
    mismatched = sorted(
        path
        for path, content in expected.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    )

    for path in stale:
        print(f"stale Claude AGENTS.md bridge: {path.relative_to(REPO_ROOT)}")
    for path in mismatched:
        print(f"stale Claude AGENTS.md bridge: {path.relative_to(REPO_ROOT)}")
    return 1 if stale or mismatched else 0


def _write_claude_bridges() -> None:
    expected = _claude_bridge_outputs()
    for path, content in expected.items():
        if not path.is_file():
            continue
        current = path.read_text(encoding="utf-8")
        if current != content and not current.startswith(CLAUDE_BRIDGE_MARKER):
            rel_path = path.relative_to(REPO_ROOT)
            raise RuntimeError(
                f"refusing to overwrite non-generated Claude instruction: {rel_path}"
            )

    for path in _existing_claude_bridge_paths() - expected.keys():
        path.unlink()
    for path, content in expected.items():
        path.write_text(content, encoding="utf-8")


def _preview_claude_bridges() -> int:
    expected = _claude_bridge_outputs()
    actual_paths = _existing_claude_bridge_paths()
    stale = sorted(actual_paths - expected.keys())
    changed: list[Path] = []
    conflicts: list[Path] = []

    for path, content in expected.items():
        if not path.is_file():
            changed.append(path)
            continue
        current = path.read_text(encoding="utf-8")
        if current == content:
            continue
        if current.startswith(CLAUDE_BRIDGE_MARKER):
            changed.append(path)
        else:
            conflicts.append(path)

    for path in sorted(changed):
        print(f"would update Claude AGENTS.md bridge: {path.relative_to(REPO_ROOT)}")
    for path in stale:
        print(f"would remove Claude AGENTS.md bridge: {path.relative_to(REPO_ROOT)}")
    for path in sorted(conflicts):
        rel = path.relative_to(REPO_ROOT)
        print(f"Claude instruction conflicts with generated bridge: {rel}")
    return 1 if conflicts else 0


def _sync_sources(args: Sequence[str]) -> int:
    returncode = _run(args)
    if returncode != 0:
        return returncode
    returncode = _run_generate()
    if returncode != 0:
        return returncode
    _write_claude_bridges()
    return 0


def _validate() -> int:
    before = _tracked_diff()
    returncode = _sync_sources(_SOURCE_ACTIONS["install"])
    if returncode != 0:
        return returncode
    if _tracked_diff() != before:
        print(
            "Rulesync source installation changed tracked projections; "
            "regenerate and commit them.",
            file=sys.stderr,
        )
        return 1

    returncode = _run(_ACTIONS["doctor"])
    if returncode != 0:
        return returncode
    returncode = _run(_ACTIONS["check"])
    if returncode != 0:
        return returncode
    return _check_claude_bridges()


def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Run Rulesync using repository rulesync.jsonc and compatibility "
            "projections."
        ),
    )
    parser.add_argument(
        "action",
        choices=(*_SOURCE_ACTIONS, *_ACTIONS, "validate"),
        help=(
            "install locked or update external sources, "
            "preview or generate projections, "
            "check drift, run doctor, or validate the locked projection state"
        ),
    )
    args = parser.parse_args()

    try:
        if args.action == "validate":
            return _validate()
        if args.action in _SOURCE_ACTIONS:
            return _sync_sources(_SOURCE_ACTIONS[args.action])

        if args.action == "generate":
            returncode = _run_generate()
        else:
            returncode = _run(_ACTIONS[args.action])
        if returncode != 0:
            return returncode
        if args.action == "generate":
            _write_claude_bridges()
            return 0
        if args.action == "check":
            return _check_claude_bridges()
        if args.action == "preview":
            return _preview_claude_bridges()
        return 0
    except RuntimeError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
