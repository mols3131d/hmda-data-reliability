#!/usr/bin/env python3
"""Run Rulesync and validate repository-local compatibility projections."""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from collections.abc import Sequence
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
CLAUDE_BRIDGE_NAME = "CLAUDE.md"
CLAUDE_BRIDGE_MARKER = "<!-- Generated by scripts/rulesync.py from sibling AGENTS.md. -->"
CLAUDE_BRIDGE_CONTENT = f"{CLAUDE_BRIDGE_MARKER}\n\n@AGENTS.md\n"

_SOURCE_ACTIONS: dict[str, tuple[str, ...]] = {
    "install": ("install",),
    "update": ("install", "--update"),
}
_ACTIONS: dict[str, tuple[str, ...]] = {
    "preview": ("generate", "--dry-run"),
    "generate": ("generate",),
    "check": ("generate", "--check"),
    "doctor": ("doctor", "--strict"),
}


def _npx_command(args: Sequence[str]) -> list[str]:
    executable = shutil.which("npx.cmd") if os.name == "nt" else shutil.which("npx")
    if executable is None:
        executable = shutil.which("npx")
    if executable is None:
        raise RuntimeError("npx is required to run Rulesync.")
    return [executable, "--yes", "rulesync@latest", *args]


def _run(args: Sequence[str], *, cwd: Path = REPO_ROOT) -> int:
    command = _npx_command(args)
    if os.name == "nt":
        command_line = subprocess.list2cmdline(command)
        return subprocess.run(
            ["cmd.exe", "/d", "/s", "/c", command_line],
            cwd=cwd,
            check=False,
        ).returncode
    return subprocess.run(command, cwd=cwd, check=False).returncode


def _repository_paths() -> list[Path]:
    result = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        raise RuntimeError("git ls-files failed while discovering instruction files.")
    return [Path(line) for line in result.stdout.splitlines() if line]


def _agent_instruction_paths() -> list[Path]:
    return sorted(path for path in _repository_paths() if path.name == "AGENTS.md")


def _claude_bridge_outputs() -> dict[Path, str]:
    return {
        REPO_ROOT / agents_path.with_name(CLAUDE_BRIDGE_NAME): CLAUDE_BRIDGE_CONTENT
        for agents_path in _agent_instruction_paths()
    }


def _existing_claude_bridge_paths() -> set[Path]:
    result: set[Path] = set()
    for relative_path in _repository_paths():
        if relative_path.name != CLAUDE_BRIDGE_NAME:
            continue
        path = REPO_ROOT / relative_path
        if path.is_file() and path.read_text(encoding="utf-8").startswith(CLAUDE_BRIDGE_MARKER):
            result.add(path)
    return result


def _check_claude_bridges() -> int:
    expected = _claude_bridge_outputs()
    actual_paths = _existing_claude_bridge_paths()
    stale = sorted(actual_paths - expected.keys())
    mismatched = sorted(
        path
        for path, content in expected.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    )

    for path in stale:
        print(f"stale Claude AGENTS.md bridge: {path.relative_to(REPO_ROOT)}")
    for path in mismatched:
        print(f"stale Claude AGENTS.md bridge: {path.relative_to(REPO_ROOT)}")
    return 1 if stale or mismatched else 0


def _write_claude_bridges() -> None:
    expected = _claude_bridge_outputs()
    for path, content in expected.items():
        if not path.is_file():
            continue
        current = path.read_text(encoding="utf-8")
        if current != content and not current.startswith(CLAUDE_BRIDGE_MARKER):
            raise RuntimeError(
                f"refusing to overwrite non-generated Claude instruction: {path.relative_to(REPO_ROOT)}"
            )

    for path in _existing_claude_bridge_paths() - expected.keys():
        path.unlink()
    for path, content in expected.items():
        path.write_text(content, encoding="utf-8")


def _preview_claude_bridges() -> int:
    expected = _claude_bridge_outputs()
    actual_paths = _existing_claude_bridge_paths()
    stale = sorted(actual_paths - expected.keys())
    changed: list[Path] = []
    conflicts: list[Path] = []

    for path, content in expected.items():
        if not path.is_file():
            changed.append(path)
            continue
        current = path.read_text(encoding="utf-8")
        if current == content:
            continue
        if current.startswith(CLAUDE_BRIDGE_MARKER):
            changed.append(path)
        else:
            conflicts.append(path)

    for path in sorted(changed):
        print(f"would update Claude AGENTS.md bridge: {path.relative_to(REPO_ROOT)}")
    for path in stale:
        print(f"would remove Claude AGENTS.md bridge: {path.relative_to(REPO_ROOT)}")
    for path in sorted(conflicts):
        print(f"Claude instruction conflicts with generated bridge: {path.relative_to(REPO_ROOT)}")
    return 1 if conflicts else 0


def _sync_sources(args: Sequence[str]) -> int:
    returncode = _run(args)
    if returncode != 0:
        return returncode
    returncode = _run(_ACTIONS["generate"])
    if returncode != 0:
        return returncode
    _write_claude_bridges()
    return 0


def _validate() -> int:
    returncode = _run(_ACTIONS["doctor"])
    if returncode != 0:
        return returncode
    returncode = _run(_ACTIONS["check"])
    if returncode != 0:
        return returncode
    return _check_claude_bridges()


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Run Rulesync using repository rulesync.jsonc and compatibility projections.",
    )
    parser.add_argument(
        "action",
        choices=(*_SOURCE_ACTIONS, *_ACTIONS, "validate"),
        help=(
            "install or update external sources, preview or generate projections, "
            "check drift, run doctor, or run doctor + projection checks"
        ),
    )
    args = parser.parse_args()

    try:
        if args.action == "validate":
            return _validate()
        if args.action in _SOURCE_ACTIONS:
            return _sync_sources(_SOURCE_ACTIONS[args.action])

        returncode = _run(_ACTIONS[args.action])
        if returncode != 0:
            return returncode
        if args.action == "generate":
            _write_claude_bridges()
            return 0
        if args.action == "check":
            return _check_claude_bridges()
        if args.action == "preview":
            return _preview_claude_bridges()
        return 0
    except RuntimeError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
